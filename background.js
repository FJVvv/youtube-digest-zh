const CHAT_TRANSCRIPT_MAX_CHARS = 60_000;
const CHAT_HISTORY_MAX_MESSAGES = 24;
const CHAT_MAX_TOKENS = 2_048;

/**
 * Renders the video length as M:SS for the prompt. The side panel normally
 * sends seconds; anything unusable falls back to "Unknown".
 */
function formatVideoDurationForChat(videoDuration) {
  if (typeof videoDuration === "number" && Number.isFinite(videoDuration)) {
    const totalSeconds = Math.max(0, Math.floor(videoDuration));
    const minutes = Math.floor(totalSeconds / 60);
    const seconds = totalSeconds % 60;
    return `${minutes}:${String(seconds).padStart(2, "0")}`;
  }
  const raw = String(videoDuration ?? "").trim();
  if (!raw) return "Unknown";
  // Already in M:SS / H:MM:SS form — pass it through untouched.
  if (/^\d{1,3}:\d{2}(:\d{2})?$/.test(raw)) return raw;
  if (/^\d+(\.\d+)?$/.test(raw)) {
    return formatVideoDurationForChat(Number(raw));
  }
  return "Unknown";
}

/**
 * Keeps the beginning and the end of an over-long transcript so the model sees
 * both the setup and the conclusion of the video.
 */
function truncateTranscriptForChat(
  transcriptText,
  maxChars = CHAT_TRANSCRIPT_MAX_CHARS,
) {
  const text = String(transcriptText || "").trim();
  if (text.length <= maxChars) return text;
  const headLength = Math.floor(maxChars * 0.7);
  const tailLength = maxChars - headLength;
  return [
    text.slice(0, headLength),
    "[…字幕中间部分因长度限制已省略：未覆盖的内容不要猜测…]",
    text.slice(text.length - tailLength),
  ].join("\n\n");
}

/**
 * Keeps only well-formed user/assistant turns and caps how much history is
 * resent with each question.
 */
function normalizeChatHistory(messages) {
  if (!Array.isArray(messages)) return [];
  return messages
    .filter(
      (message) =>
        message &&
        (message.role === "user" || message.role === "assistant") &&
        typeof message.content === "string" &&
        message.content.trim(),
    )
    .map((message) => ({
      role: message.role,
      content: message.content.trim(),
    }))
    .slice(-CHAT_HISTORY_MAX_MESSAGES);
}

/**
 * Answers one question about the current video.
 *
 * The side panel owns the conversation state and sends the prior turns, so this
 * handler stays stateless between questions.
 */
async function handleChatAsk({
  transcriptText,
  videoTitle,
  channelName,
  videoDescription,
  videoDuration,
  videoUrl,
  analysisSummary,
  messages,
  question,
}) {
  try {
    const settings = await getSettings();
    if (!settings.aiApiKey) {
      return {
        success: false,
        error: "NO_AI_KEY",
        message: "未配置 AI API 密钥。请打开 YouTube Digest 设置。",
      };
    }

    const trimmedQuestion = String(question || "").trim();
    if (!trimmedQuestion) {
      return {
        success: false,
        error: "EMPTY_QUESTION",
        message: "请输入你的问题。",
      };
    }

    const transcript = truncateTranscriptForChat(transcriptText);
    if (!transcript) {
      return {
        success: false,
        error: "CHAT_NO_TRANSCRIPT",
        message: "当前视频还没有字幕，无法进行对话。",
      };
    }

    const promptVariables = {
      videoTitle: videoTitle || "Unknown",
      channelName: channelName || "Unknown",
      videoDuration: formatVideoDurationForChat(videoDuration),
      videoUrl: String(videoUrl || "").trim() || "Unknown",
      videoDescription: videoDescription || "No description available",
      analysisSummary: String(analysisSummary || "").trim() || "（无）",
      transcriptText: transcript,
    };
    const systemPrompt = await loadPromptSection(
      "chat.md",
      "System prompt",
      promptVariables,
    );
    const userPrompt = await loadPromptSection("chat.md", "User prompt", {
      question: trimmedQuestion,
    });

    // The side panel usually appends the pending question to the history it
    // sends, so the last turn can already be this same question. Drop it here
    // instead of asking the model the same thing twice in a row.
    const history = normalizeChatHistory(messages);
    const lastHistoryMessage = history[history.length - 1];
    if (
      lastHistoryMessage &&
      lastHistoryMessage.role === "user" &&
      lastHistoryMessage.content.trim() === trimmedQuestion
    ) {
      history.pop();
    }

    const { text } = await requestAiCompletion({
      maxTokens: CHAT_MAX_TOKENS,
      temperature: 0.6,
      messages: [
        { role: "system", content: systemPrompt },
        ...history,
        { role: "user", content: userPrompt },
      ],
    });

    return {
      success: true,
      answer: String(text || "").trim(),
      model: settings.aiModel,
    };
  } catch (error) {
    console.error("Chat error:", error);
    if (error.status === 401) {
      return {
        success: false,
        error: "INVALID_AI_KEY",
        message: "AI 服务拒绝了该 API 密钥。",
      };
    }
    if (error.status === 429) {
      return {
        success: false,
        error: "RATE_LIMITED",
        message: "AI 服务请求频率受限，请稍后重试。",
      };
    }
    if (
      error.code === "AI_IDLE_TIMEOUT" ||
      error.code === "AI_HARD_TIMEOUT"
    ) {
      return {
        success: false,
        error: "AI_TIMEOUT",
        message: "AI 服务响应超时，请重试。",
      };
    }
    return {
      success: false,
      error: error.code || "CHAT_FAILED",
      message: error.message || "对话失败",
    };
  }
}


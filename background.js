/**
 * Formats caption cues captured from the YouTube player into the transcript
 * shape used by the side panel and the AI prompts.
 */
function formatYouTubeCues(cues, language) {
  const transcript = [];
  let transcriptTextPlain = "";
  let transcriptTextTimestamped = "";
  for (const cue of Array.isArray(cues) ? cues : []) {
    const text = String(cue?.text || "")
      .replace(/>> ?/g, "")
      .trim();
    if (!text) continue;
    const startSeconds = Math.max(0, Math.floor(Number(cue.start) || 0));
    const minutes = Math.floor(startSeconds / 60);
    const seconds = startSeconds % 60;
    const timestamp = `${minutes}:${String(seconds).padStart(2, "0")}`;
    transcript.push({
      text,
      start: startSeconds,
      duration: Math.max(0, Math.floor(Number(cue.duration) || 0)),
      language: cue.language || language || null,
    });
    transcriptTextPlain += `${text} `;
    transcriptTextTimestamped += `[${timestamp}] ${text}\n`;
  }
  if (transcript.length === 0) return null;
  return {
    success: true,
    transcriptSource: "youtube",
    transcript,
    transcriptText: transcriptTextPlain.trim(),
    transcriptTextTimestamped: transcriptTextTimestamped.trim(),
    language: language || transcript[0].language || null,
  };
}

/**
 * Resolves the YouTube tab that should provide captions. The side panel passes
 * its tab id, but the active tab is a safe fallback for direct calls.
 */
async function resolveYouTubeTabId(tabId) {
  if (Number.isInteger(tabId)) return tabId;
  const tabs = await chrome.tabs.query({
    active: true,
    lastFocusedWindow: true,
  });
  return tabs?.[0]?.id ?? null;
}

/**
 * Tries to read the video's own caption track for free.
 * Returns { ok: true, transcript } on success, or { ok: false, code } so the
 * caller can decide between the Supadata fallback and a plain error.
 */
async function fetchYouTubeTranscript(videoId, tabId) {
  try {
    const resolvedTabId = await resolveYouTubeTabId(tabId);
    if (!resolvedTabId) return { ok: false, code: "NO_YOUTUBE_TAB" };
    const timeout = new Promise((resolve) =>
      setTimeout(() => resolve(null), FREE_CAPTIONS_TIMEOUT_MS),
    );
    const response = await Promise.race([
      chrome.tabs.sendMessage(resolvedTabId, {
        action: "extractFreeCaptions",
        videoId,
      }),
      timeout,
    ]);
    if (
      !response ||
      response.success !== true ||
      !Array.isArray(response.cues)
    ) {
      const code = String(
        response?.code ||
          response?.error ||
          response?.message ||
          "EMPTY_RESPONSE",
      );
      debugLog(
        "[YouTube Digest BG] Free caption extraction unavailable:",
        code,
      );
      return { ok: false, code };
    }
    const transcript = formatYouTubeCues(response.cues, response.language);
    if (!transcript) return { ok: false, code: "EMPTY_CUES" };
    return { ok: true, transcript };
  } catch (error) {
    debugLog("[YouTube Digest BG] Free caption extraction failed:", error);
    return {
      ok: false,
      code: error?.name === "TimeoutError" ? "TIMEOUT" : "CAPTION_FETCH_FAILED",
    };
  }
}

/**
 * Decides which transcript source this request should use. An explicit
 * per-request value wins over the saved setting; unknown values fall back to
 * the free-captions-first behaviour.
 */
function resolveTranscriptSource(requestedSource, savedSource) {
  for (const candidate of [requestedSource, savedSource]) {
    if (candidate === "youtube" || candidate === "supadata") return candidate;
  }
  return "auto";
}

/**
 * Fetches the transcript for a YouTube video.
 *
 * Reads YouTube's own captions first (free), then falls back to Supadata when
 * it is configured and the free path failed.
 *
 * Supadata is a specialized service that reliably extracts transcripts
 * from YouTube videos. It stays available as an opt-in fallback (see the
 * 字幕服务 setting) so a video's own captions are always preferred.
 *
 * API Docs: https://docs.supadata.ai
 *
 * @param {string} videoId - The YouTube video ID (e.g., "dQw4w9WgXcQ")
 * @param {number|null} tabId - The YouTube tab that should provide captions
 * @param {string} transcriptSource - "auto" (free captions, then Supadata), "youtube" (free only), or "supadata"
 * @returns {Object} - { success, transcriptSource, transcript, transcriptText, transcriptTextTimestamped, language, freeCaptionFailure? } or { success: false, error, code?, message }
 */
async function handleFetchTranscript(
  videoId,
  tabId = null,
  transcriptSource = "auto",
) {
  try {
    const settings = await getSettings();
    const source = resolveTranscriptSource(
      transcriptSource,
      settings.transcriptSource,
    );
    let freeCaptionFailure = null;

    // Free path: parse the captions YouTube already loaded in the page.
    if (source === "youtube" || source === "auto") {
      const freeResult = await fetchYouTubeTranscript(videoId, tabId);
      if (freeResult.ok) return freeResult.transcript;
      freeCaptionFailure = freeResult.code || "FREE_CAPTIONS_UNAVAILABLE";
      // "youtube" means the user explicitly asked to never call Supadata.
      if (source === "youtube") {
        return {
          success: false,
          error: "FREE_CAPTIONS_FAILED",
          code: freeCaptionFailure,
          message: `无法读取 YouTube 自带字幕（原因：${freeCaptionFailure}）。当前字幕来源设置为「仅免费字幕」，不会调用 Supadata。请在设置中改用「免费字幕优先」或「仅使用 Supadata」，或打开一个有字幕的视频。`,
        };
      }
    }

    if (!settings.supadataApiKey) {
      return {
        success: false,
        error: "NO_SUPADATA_KEY",
        message:
          source === "auto"
            ? "无法读取 YouTube 自带字幕，且未配置 Supadata API 密钥。请打开 YouTube Digest 设置。"
            : "未配置 Supadata API 密钥。请打开 YouTube Digest 设置。",
      };
    }

    // Share only the canonical watch URL. This strips playlist, referral,
    // timestamp, and other browsing parameters from the active tab URL.
    const canonicalVideoUrl = YTD_SETTINGS.canonicalYouTubeUrl(videoId);
    // Using the universal transcript endpoint with text=false to get timestamped chunks
    const apiUrl = new URL("https://api.supadata.ai/v1/transcript");
    apiUrl.searchParams.set("url", canonicalVideoUrl);
    apiUrl.searchParams.set("text", "false"); // Get timestamped chunks, not plain text
    apiUrl.searchParams.set("lang", "en"); // Prefer English
    // Caption-only product scope: never fall back to paid AI transcription.
    apiUrl.searchParams.set("mode", "native");

    // Make the API request
    const response = await fetch(apiUrl.toString(), {
      method: "GET",
      headers: {
        "x-api-key": settings.supadataApiKey,
      },
    });

    // Handle async jobs (for videos > 20 minutes, Supadata returns a job ID)
    if (response.status === 202) {
      const jobData = await response.json();
      // Poll for the result
      const jobResult = await pollTranscriptJob(
        jobData.jobId,
        settings.supadataApiKey,
      );
      if (jobResult && jobResult.success && freeCaptionFailure) {
        jobResult.freeCaptionFailure = freeCaptionFailure;
      }
      return jobResult;
    }

    if (response.status === 206) {
      return {
        success: false,
        error: "NO_TRANSCRIPT",
        message: "此视频没有可用的原生字幕。",
      };
    }

    if (!response.ok) {
      const errorData = await response.json().catch(() => ({}));
      if (response.status === 401) {
        return {
          success: false,
          error: "INVALID_SUPADATA_KEY",
          message: "Supadata API 密钥无效。请打开 YouTube Digest 设置。",
        };
      }
      if (response.status === 404) {
        return {
          success: false,
          error: "NO_TRANSCRIPT",
          message: "未找到此视频的字幕。",
        };
      }
      if (response.status === 429) {
        return {
          success: false,
          error: "RATE_LIMITED",
          message:
            "Supadata 请求次数已达上限，请稍等一分钟再试。",
        };
      }
      throw new Error(
        errorData.message || `Supadata API 错误：${response.status}`,
      );
    }

    const data = await response.json();

    // Parse the response into our internal format
    // Supadata returns: { content: [{ text, offset, duration, lang }], lang, availableLangs }
    const transcript = [];
    let transcriptTextPlain = ""; // Plain text for display/export
    let transcriptTextTimestamped = ""; // Timestamped text for AI analysis

    if (data.content && Array.isArray(data.content)) {
      for (const chunk of data.content) {
        if (chunk.text) {
          // Clean up caption artifacts:
          // ">>" = speaker change marker from YouTube auto-captions
          const cleanText = chunk.text.replace(/>> ?/g, "").trim();
          if (!cleanText) continue; // Skip if nothing left after cleanup

          // offset is in milliseconds, convert to seconds
          const startSeconds = Math.floor((chunk.offset || 0) / 1000);
          const minutes = Math.floor(startSeconds / 60);
          const seconds = startSeconds % 60;
          const timestamp = `${minutes}:${String(seconds).padStart(2, "0")}`;

          transcript.push({
            text: cleanText,
            start: startSeconds,
            duration: Math.floor((chunk.duration || 0) / 1000),
            language: chunk.lang || data.lang || null,
          });

          // Plain text without timestamps (for display/export)
          transcriptTextPlain += cleanText + " ";

          // Timestamped text for DeepSeek (format: [MM:SS] text)
          // This allows the model to reference actual transcript positions.
          transcriptTextTimestamped += `[${timestamp}] ${cleanText}\n`;
        }
      }
    }

    if (transcript.length === 0) {
      return {
        success: false,
        error: "EMPTY_TRANSCRIPT",
        message: "Supadata 未返回此视频的字幕内容。",
      };
    }

    const result = {
      success: true,
      transcriptSource: "supadata",
      transcript: transcript,
      transcriptText: transcriptTextPlain.trim(), // For display
      transcriptTextTimestamped: transcriptTextTimestamped.trim(), // For AI
      language: typeof data.lang === "string" ? data.lang : null,
    };
    // Tell the panel why the free path was skipped, so a fallback that spends
    // a Supadata credit is never silent.
    if (freeCaptionFailure) result.freeCaptionFailure = freeCaptionFailure;
    return result;
  } catch (error) {
    console.error("Transcript fetch error:", error);
    return {
      success: false,
      error: error.message || "获取字幕失败",
    };
  }
}

/**
 * Polls for transcript job completion (for long videos).
 * Supadata processes videos > 20 minutes asynchronously.
 *
 * @param {string} jobId - The job ID returned by the initial request
 * @returns {Object} - Same format as handleFetchTranscript
 */
async function pollTranscriptJob(jobId, supadataApiKey) {
  const maxAttempts = 60; // Max 60 seconds of polling
  const pollInterval = 1000; // Poll every 1 second

  for (let attempt = 0; attempt < maxAttempts; attempt++) {
    // Wait before polling
    await new Promise((resolve) => setTimeout(resolve, pollInterval));

    const response = await fetch(
      `https://api.supadata.ai/v1/transcript/${encodeURIComponent(jobId)}`,
      {
        headers: { "x-api-key": supadataApiKey },
      },
    );

    if (!response.ok) {
      throw new Error(`轮询任务失败：${response.status}`);
    }

    const data = await response.json();

    if (data.status === "completed") {
      // Parse the completed transcript
      const transcript = [];
      let transcriptTextPlain = "";
      let transcriptTextTimestamped = "";

      if (data.content && Array.isArray(data.content)) {
        for (const chunk of data.content) {
          if (chunk.text) {
            // Clean up caption artifacts (">>" = speaker change marker)
            const cleanText = chunk.text.replace(/>> ?/g, "").trim();
            if (!cleanText) continue;

            const startSeconds = Math.floor((chunk.offset || 0) / 1000);
            const minutes = Math.floor(startSeconds / 60);
            const seconds = startSeconds % 60;
            const timestamp = `${minutes}:${String(seconds).padStart(2, "0")}`;

            transcript.push({
              text: cleanText,
              start: startSeconds,
              duration: Math.floor((chunk.duration || 0) / 1000),
              language: chunk.lang || data.lang || null,
            });
            transcriptTextPlain += cleanText + " ";
            transcriptTextTimestamped += `[${timestamp}] ${chunk.text}\n`;
          }
        }
      }

      return {
        success: true,
        transcriptSource: "supadata",
        transcript: transcript,
        transcriptText: transcriptTextPlain.trim(),
        transcriptTextTimestamped: transcriptTextTimestamped.trim(),
        language: typeof data.lang === "string" ? data.lang : null,
      };
    }

    if (data.status === "failed") {
      throw new Error("字幕处理失败");
    }

    // Status is 'queued' or 'active' — keep polling
  }

  throw new Error("字幕处理超时");
}

